  *) printf 'unknown network: %s (testnet or mainnet)\n' "$NETWORK" >&2; return 2 ;;
esac
ENV_FILE="$LADDER/.env.deploy-$NETWORK"
# The checks of verify-chain.mjs cost about 20 MON at a 100 gwei base fee; the protocol about 16.3M gas, the ladder
# about 3M. Monad charges the gas limit of a transaction, so the balance must cover the limits, not the use.
MIN_BALANCE=30
# Where the Vercel variables of this network go. The first season goes to Production from the testnet run; the
# mainnet run replaces Production and leaves Preview on the testnet.
if [[ "$NETWORK" == mainnet ]]; then VERCEL_ENVS=(production); TOTAL_STAGES=14; else VERCEL_ENVS=(production preview); TOTAL_STAGES=13; fi

if (( DRY_RUN )); then
  printf 'Tank ladder deployment wizard — %s (chain %s), %s stages, values in %s\n\n' "$NETWORK_NAME" "$CHAIN_ID" "$TOTAL_STAGES" "$ENV_FILE"
  printf '  1  Tools and network\n  2  Deployer key\n  3  Fund the deployer\n  4  Protocol contracts (official Factory)\n  5  Season end block\n'
  printf '  6  Ladder contract\n  7  data/deployments.json\n  8  Chain checks (verify-chain.mjs)\n  9  Vercel project\n 10  Neon database\n'
  printf ' 11  Privy app\n 12  Vercel environment variables\n 13  Walk through the live page\n'
  [[ "$NETWORK" == mainnet ]] && printf ' 14  Contest rules: known limits\n'
  printf '\ntools: forge %s · node %s · vercel CLI %s · openssl %s\n' "$(forge_bin || echo missing)" "$(command -v node >/dev/null 2>&1 && node --version || echo missing)" "$(command -v vercel >/dev/null 2>&1 && echo yes || echo no)" "$(command -v openssl >/dev/null 2>&1 && echo yes || echo no)"
  return 0
fi

banner "Tank ladder on $NETWORK_NAME"

# ── 1 ─────────────────────────────────────────────────────────────────────
stage "Tools and network"
say "This run targets $NETWORK_NAME (chain id $CHAIN_ID) through $RPC_URL."
