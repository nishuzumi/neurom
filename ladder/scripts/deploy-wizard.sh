  LADDER_ADDRESS=$(LADDER_FACTORY="$LADDER_FACTORY" LADDER_END_BLOCK="$LADDER_END_BLOCK" forge_deploy DeployLadder.s.sol ladder TankLadder) || return 1
  say "ladder deployed at $LADDER_ADDRESS ($EXPLORER/address/$LADDER_ADDRESS)"
