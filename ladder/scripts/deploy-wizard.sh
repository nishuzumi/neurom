# node_module "code" args…: run ESM `code` with the repo's node_modules (process.argv[1..] = args).
node_module() { local code="$1"; shift; (cd "$ROOT" && node --input-type=module -e "$code" -- "$@"); }

# chain_block RPC → the latest block number.
chain_block() {
  node_module 'import { JsonRpcProvider } from "ethers"; const p = new JsonRpcProvider(process.argv[1], undefined, { staticNetwork: true }); console.log(await p.getBlockNumber()); p.destroy();' "$1"
}
# chain_id RPC → the chain id the RPC reports.
chain_id() {
  node_module 'import { JsonRpcProvider } from "ethers"; const p = new JsonRpcProvider(process.argv[1]); console.log(String((await p.getNetwork()).chainId)); p.destroy();' "$1"
}
# balance_of RPC ADDRESS → the balance in MON (4 decimals).
balance_of() {
  node_module 'import { JsonRpcProvider, formatEther } from "ethers"; const p = new JsonRpcProvider(process.argv[1], undefined, { staticNetwork: true }); console.log(Number(formatEther(await p.getBalance(process.argv[2]))).toFixed(4)); p.destroy();' "$1" "$2"
}
# address_of_key KEY → the address of a private key.
address_of_key() { node_module 'import { Wallet } from "ethers"; console.log(new Wallet(process.argv[1]).address);' "$1"; }
# new_key → a fresh random private key.
new_key() { node_module 'import { Wallet } from "ethers"; console.log(Wallet.createRandom().privateKey);'; }
# deployment_field CHAIN FIELD → the field of data/deployments.json for the chain ("" when null).
deployment_field() {
  node_module 'import { readFileSync } from "node:fs"; const j = JSON.parse(readFileSync(process.argv[1], "utf8")); console.log(j[process.argv[2]]?.[process.argv[3]] ?? "");' "$DEPLOYMENTS" "$1" "$2"
}
# write_deployment CHAIN FACTORY LADDER: set the two addresses of the chain in data/deployments.json. A textual edit
# of the chain's block, so the file keeps its key order and comment (JSON.stringify would sort the numeric keys).
write_deployment() {
  node_module 'import { readFileSync, writeFileSync } from "node:fs";
    const [file, chain, factory, ladder] = process.argv.slice(1);
    const text = readFileSync(file, "utf8");
    const block = new RegExp(`("${chain}":\\s*\\{[^}]*)\\}`);
    if (!block.test(text)) throw new Error(`chain ${chain} is not in ${file}`);
    const set = (body, key, value) => { const re = new RegExp(`("${key}":\\s*)(null|"0x[0-9a-fA-F]{40}")`); if (!re.test(body)) throw new Error(`no "${key}" in the block of chain ${chain}`); return body.replace(re, `$1"${value}"`); };
    const out = text.replace(block, (_, body) => set(set(body, "factory", factory), "ladder", ladder) + "}");
    JSON.parse(out);
    writeFileSync(file, out);' "$DEPLOYMENTS" "$1" "$2" "$3"
}
# forge_bin → the forge binary: $FORGE, ~/.foundry/bin/forge or forge on PATH; fails when none exists.
forge_bin() {
  if [[ -n "${FORGE:-}" && -x "$FORGE" ]]; then printf '%s' "$FORGE"
  elif [[ -x "$HOME/.foundry/bin/forge" ]]; then printf '%s' "$HOME/.foundry/bin/forge"
  elif command -v forge >/dev/null 2>&1; then command -v forge
  else return 1; fi
}
# forge_deploy SCRIPT NAME TYPE: run a forge script with the deployer key and print (stdout) only the address the
# script returns as `NAME: contract TYPE 0x…`; the progress and forge's output go to the terminal (stderr) and to
# $FORGE_LOG. Fails when the address is not found. Callers capture it: ADDR=$(forge_deploy …).
forge_deploy() {
  local script="$1" name="$2" type="$3" address
  FORGE_LOG=$(mktemp "${TMPDIR:-/tmp}/forge-script.XXXXXX")
  say "running forge script $script against $RPC_URL (log: $FORGE_LOG)…" >&2
  if ! (cd "$CONTRACTS" && "$FORGE_BIN" script "script/$script" --rpc-url "$RPC_URL" --private-key "$DEPLOYER_PRIVATE_KEY" --broadcast 2>&1 | tee "$FORGE_LOG" >&2); then
    warn "forge script failed; see $FORGE_LOG" >&2
    return 1
  fi
  address=$(grep -E "^\s*$name: contract $type 0x[0-9a-fA-F]{40}" "$FORGE_LOG" | tail -n1 | grep -oE '0x[0-9a-fA-F]{40}') || true
  [[ -n "$address" ]] || { warn "could not read the $name address from the forge output; see $FORGE_LOG" >&2; return 1; }
  printf '%s' "$address"
}
# vercel_env NAME VALUE ENV…: set a Vercel environment variable for each environment through the CLI (replaces an
# existing one). Records a SKIPPED item when the CLI is not linked.
vercel_env() {
  local name="$1" value="$2"; shift 2
  local env_name
  for env_name in "$@"; do
    (cd "$LADDER" && vercel env rm "$name" "$env_name" --yes >/dev/null 2>&1 || true)
    if (cd "$LADDER" && printf '%s' "$value" | vercel env add "$name" "$env_name" >/dev/null 2>&1); then
      printf '  %s✓ set%s Vercel %s (%s)\n' "$GREEN" "$RESET" "$name" "$env_name"
    else
      SKIPPED+=("Vercel env $name ($env_name): set it in the dashboard")
      warn "could not set $name for $env_name through the Vercel CLI; set it in the dashboard"
    fi
  done
}

run_wizard() {

