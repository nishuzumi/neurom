command -v node >/dev/null 2>&1 || { warn "node is missing (>= 22.12). Install it and re-run."; return 1; }
[[ -d "$ROOT/node_modules/ethers" ]] || { warn "node_modules is missing: run 'npm install' in $ROOT first."; return 1; }
FORGE_BIN=$(forge_bin) || { warn "forge is missing. Install Foundry >= 1.8 (https://getfoundry.sh) or set FORGE=/path/to/forge."; return 1; }
