say "latest block $b1, about $(printf '%d.%02d' $(( rate / 100 )) $(( rate % 100 ))) blocks/s, about $per_day blocks per day."
ask SEASON_DAYS "Season length in days (e.g. 30):" || return 1
suggested=$(( b1 + SEASON_DAYS * per_day ))
say "suggested end block: $suggested (block $b1 + $SEASON_DAYS days)."
ask LADDER_END_BLOCK "End block (Enter = $suggested):" || LADDER_END_BLOCK=""
[[ -z "$LADDER_END_BLOCK" ]] && LADDER_END_BLOCK="$suggested"
[[ "$LADDER_END_BLOCK" =~ ^[0-9]+$ && "$LADDER_END_BLOCK" -gt "$b1" ]] || { warn "the end block must be a number above $b1"; return 1; }
write_env SEASON_DAYS "$SEASON_DAYS"
