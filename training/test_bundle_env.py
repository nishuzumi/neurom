"""bundle_env.py, bundle_loop.py and bundle_train.Session.run_steps must step exactly like frontend/core/runner.js,
frontend/core/loop.js and its lockstep runner. These tests:
    - replay the parity corpus training/fixtures/bundle-env.json (generated by training/fixtures/bundle-env.mjs, checked
      again in JS by bundle-env.test.mjs) with every lane in one batch.
    - cover the batched-only rules: the state of a network tool per lane (the potentials of a LIF tool, the state of a
      nested tool), ADR 0014."""
import json
import unittest
from pathlib import Path

import numpy as np

import bundle_env
import bundle_loop
import bundle_train
import ir

FIXTURES = json.loads((Path(__file__).resolve().parent / 'fixtures' / 'bundle-env.json').read_text())


def plain(t, value, i):
    return ir.lane(t, value, i)


def lane_value(v, i):
    return v[i].tolist() if v.ndim > 1 else float(v[i])


class EnvParity(unittest.TestCase):
    def test_every_scenario_matches_the_browser_runner_lane_for_lane(self):
        for sc in FIXTURES['envs']:
            with self.subTest(scenario=sc['name']):
                env = bundle_env.create_env(sc['env'], tables=sc['tables'])
                T, lanes = sc['env']['types'], sc['lanes']
                target = bundle_env.BoundProgram(sc['objective'], [T['State']] + ([T['table']] if T.get('table') else []), 'target') if sc['objective']['kind'] == 'target' else None
                initial = env.reset([l['start'] for l in lanes])
                for i, l in enumerate(lanes): self.assertEqual(plain(T['State'], initial, i), l['initial'])
                for k in range(max(len(l['steps']) for l in lanes)):
                    live = ~env.done
                    bits = env.input()
                    y = target.run([env.state] + env.full_table(), env.B, live) if target else None
                    tr = env.step(np.array([l['steps'][k]['transition']['action'] if k < len(l['steps']) else 0 for l in lanes], dtype=np.float64))
                    for i, l in enumerate(lanes):
                        if k >= len(l['steps']):
                            self.assertFalse(tr['active'][i]); self.assertTrue(env.done[i]); continue
                        js, where = l['steps'][k], f'{sc["name"]} lane {i} step {k}'
                        self.assertTrue(tr['active'][i])
                        self.assertEqual(bits[i].tolist(), js['input'], f'{where} input')
                        self.assertEqual(plain(T['Transition'], bundle_env.transition(tr), i), js['transition'], f'{where} transition')
                        self.assertEqual(int(env.t[i]), js['t'])
                        if y is not None: self.assertEqual(y[i].tolist(), js['target'], f'{where} target')
                self.assertTrue(env.done.all())
                for i, l in enumerate(lanes): self.assertEqual(plain(T['State'], env.state, i), l['final'])


class LoopParity(unittest.TestCase):
    def test_every_loop_matches_the_browser_executor_lane_for_lane(self):
        for sc in FIXTURES['loops']:
            with self.subTest(loop=sc['name']):
                bundle, lanes = sc['bundle'], sc['lanes']
                env, lx = bundle_env.create_env(bundle['env']), bundle_loop.create_loop(bundle['loop'])
                T, nodes = bundle['env']['types'], bundle['loop']['nodes']
                env.reset([l['start'] for l in lanes]); lx.reset(env.B)
                for k in range(max(len(l['steps']) for l in lanes)):
                    live = ~env.done
                    bits = env.input()
                    out = lx.step(bits, live)
                    tr = env.step(out['action'])
                    for i, l in enumerate(lanes):
                        if k >= len(l['steps']): self.assertFalse(live[i]); continue
                        js, where = l['steps'][k], f'{sc["name"]} lane {i} step {k}'
                        ran = sorted(n for n in nodes if out['ran'][n][i])
                        self.assertEqual(bits[i].tolist(), js['bits'], f'{where} bits')
                        self.assertEqual(ran, js['ran'], f'{where} ran')
                        self.assertEqual(sorted(key for key in out['values'] if key.split('.')[0] in ran), sorted(js['values']), f'{where} value keys')
                        for key, v in js['values'].items(): self.assertEqual(lane_value(out['values'][key], i), v, f'{where} {key}')
                        self.assertEqual(float(out['action'][i]), js['action'], f'{where} action')
                        self.assertEqual(plain(T['Transition'], bundle_env.transition(tr), i), js['transition'], f'{where} transition')
                        states = lx.states()
                        self.assertEqual(sorted(states), sorted(js['voltages']), f'{where} networks with a state')
                        for net, v in js['voltages'].items(): self.assertEqual(states[net][i].tolist(), v, f'{where} {net} voltages (own ‖ tool states)')
                        tools = {nid: {port: {key: lane_value(a, i) for key, a in r.items()} for port, r in rec.items()} for nid, rec in out['tools'].items() if out['ran'][nid][i]}
                        self.assertEqual(tools, js['tools'], f'{where} tool records')
                reward = bundle_env.BoundProgram(bundle['objective'], [bundle_loop.transition_type(T['Transition'], bundle['loop'])], 'reward')
                ep = bundle_loop.run_episodes(env, lx, [s['start'] for s in sc['summaries']], reward=reward)
                self.assertEqual([{'start': s['start'], 'success': bool(ep['success'][i]), 'steps': int(ep['steps'][i]), 'return': float(ep['return'][i])} for i, s in enumerate(sc['summaries'])], sc['summaries'])


def batched(results, active, B):
    """The lanes' scripted intercept results (fixture JSON) as one batched result: `slot` [B], `bits` / `scores` [B, w],
    `tools` {port: {choice [B], data [B, D], result [B, R]}}. Lanes outside `active` read zeros."""
    first = next(results[i] for i in range(B) if active[i])
    rows = lambda get: np.array([get(results[i]) if active[i] else np.zeros_like(np.asarray(get(first), dtype=np.float64)) for i in range(B)], dtype=np.float64)
    out = {key: rows(lambda r, key=key: r[key]) for key in ('slot', 'bits', 'scores') if key in first}
    if 'tools' in first: out['tools'] = {port: {k: rows(lambda r, port=port, k=k: r['tools'][port][k]) for k in rec} for port, rec in first['tools'].items()}
    return out


def run_intercepted(bundle, tables, starts, result_of, record=False):
    """bundle_train.Session.run_steps over `starts`, the trained network answering `result_of(lane, step)` → per lane the
    steps {x, y, action, transition, reward}, only with `record`. The transition has `loop`. The reward can be None."""
    s = bundle_train.Session(bundle, tables)
    B, k, seen = len(starts), [-1], [[] for _ in starts]

    def before(): k[0] += 1

    def intercept(x, lanes, y):
        for i in np.flatnonzero(lanes): seen[i].append({'x': x[i].tolist(), 'y': None if y is None else y[i].tolist()})
        return batched([result_of(i, k[0]) if lanes[i] else None for i in range(B)], lanes, B)

    steps = s.run_steps(starts, intercept, before, record=record)
    if not record: return None
    T = bundle_loop.transition_type(bundle['env']['types']['Transition'], bundle['loop'])
    lanes = [[] for _ in starts]
    for tr, _, out in steps:
        rec, reward = s.lx.transition(tr, out), s.rewards(tr, out) if s.reward is not None else None
        for i in np.flatnonzero(tr['active']):
            lanes[i].append({**seen[i][len(lanes[i])], 'action': float(out['action'][i]), 'transition': plain(T, rec, i), 'reward': None if reward is None else float(reward[i])})
    return lanes


class LockstepParity(unittest.TestCase):
    def test_every_intercepted_case_matches_the_browser_lockstep_runner(self):
        self.assertGreaterEqual(len(FIXTURES['intercepted']), 6)
        for sc in FIXTURES['intercepted']:
            with self.subTest(case=sc['name']):
                lanes = run_intercepted(sc['bundle'], sc['tables'], [l['start'] for l in sc['lanes']], lambda i, k: sc['lanes'][i]['steps'][k]['result'], record=True)
                for i, l in enumerate(sc['lanes']):
                    self.assertEqual(len(lanes[i]), len(l['steps']), f'lane {i} steps')
                    for k, (got, js) in enumerate(zip(lanes[i], l['steps'])):
                        self.assertEqual(got, {key: js[key] for key in ('x', 'y', 'action', 'transition', 'reward')}, f'{sc["name"]} lane {i} step {k}')

    def test_every_refused_case_is_refused(self):
        for sc in FIXTURES['errors']:
            with self.subTest(case=sc['name']), self.assertRaises(ValueError):
                run_intercepted(sc['bundle'], None, sc['starts'], lambda i, k: sc['results'][i][k])


