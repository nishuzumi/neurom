    def test_quantize_region_follows_the_rule(self):
        W = [[0.5, -0.5], [1.0, 0.125]]
        # 8 bits: s = 127, codes round half up (−63.5 → −63). k = 7 is the largest with −2·127·2^k ≥ −32768
        r = bt.quantize_region(W, [0.1, -2.0], 8, 'ff')
        self.assertEqual((r['W'].tolist(), r['b'].tolist(), r['scale'], r['k'], r['clippedWeights'], r['clippedBiases']), ([[64, -63], [127, 16]], [1626, -32512], 127.0, 7, 0, 0))
        self.assertNotIn('threshold', r); self.assertEqual(r['gain'], 127 * 128)
        r = bt.quantize_region(W, [0.1, -2.0], 8, 'lif')
        self.assertEqual((r['k'], r['threshold']), (7, 16256))
        # 16 bits: s = 32767, k = 1 (−0.5·32767·2 = −32767)
        r = bt.quantize_region(W, [0.1, -0.5], 16, 'ff')
        self.assertEqual((r['W'].tolist(), r['b'].tolist(), r['scale'], r['k'], r['clippedBiases']), ([[16384, -16383], [32767, 4096]], [6553, -32767], 32767.0, 1, 0))
        # a bias that does not fit even at k = 0: k = 0, clamped, counted
        r = bt.quantize_region(W, [0.1, -2.0], 16, 'ff')
        self.assertEqual((r['b'].tolist(), r['k'], r['clippedBiases']), ([3277, -32768], 0, 1))
        r = bt.quantize_region([[1.0]], [300.0], 8, 'ff')
        self.assertEqual((r['b'].tolist(), r['k'], r['clippedBiases']), ([32767], 0, 1))
        # threshold layers: biases in [−32766, 32767] so th = 1 − b is int16
        r = bt.quantize_region([[1.0]], [-1.0], 16, 'ff')
        self.assertEqual((r['b'].tolist(), r['k'], r['clippedBiases']), ([-32767], 0, 0))
        r = bt.quantize_region([[1.0]], [-1.0], 16, 'threshold')
        self.assertEqual((r['b'].tolist(), r['k'], r['clippedBiases']), ([-32766], 0, 1))
        # LIF: the threshold code(s·2^k) must fit int32, which bounds k (s = 32767·1024: ·2^6 fits, ·2^7 does not)
        r = bt.quantize_region([[1 / 1024]], [0.0], 16, 'lif')
        self.assertEqual((r['W'].tolist(), r['k'], r['threshold']), ([[32767]], 6, 32767 * 1024 * 64))
        # all-zero weights: s = Q
        r = bt.quantize_region([[0.0, 0.0]], [0.5], 8, 'ff')
        self.assertEqual((r['W'].tolist(), r['b'].tolist(), r['scale'], r['k']), ([[0, 0]], [32512], 127.0, 9))

