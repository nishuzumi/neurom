    def test_integer_executors_match_the_runtime_semantics(self):
        dense = {'kind': 'lif', 'ticks': 2, 'leak_shift': 1, 'reset': 0, 'layers': [{'hidden': 2, 'W': [[3, 0], [0, 5]], 'b': [0, -1], 'k': 1, 'threshold': 8}], 'output': {'W': [[1, 0], [0, 1]], 'b': [1, 0], 'k': 2}}
        scores, counts, V, tools = bundle_loop.dense_step(dense, np.array([[1, 1]]), np.zeros((1, 2), dtype=np.int64))
        # currents 3·2 = 6 and 5·2 − 1 = 9. Neuron 0: 6 → 6−3+6 = 9 ≥ 8 fires (count 1). Neuron 1: 9 fires, reset 0, 9 fires (count 2)
        self.assertEqual(counts.tolist(), [[1, 2]]); self.assertEqual(scores.tolist(), [[1 * 4 + 2 * 1, 2 * 4]]); self.assertIsNone(tools)
        ff = {'kind': 'feedforward', 'ticks': 1, 'leak_shift': 0, 'reset': 0, 'layers': [{'hidden': 1, 'W': [[1, -1]], 'b': [-1], 'k': 1}], 'output': {'W': [[2]], 'b': [1], 'k': 0}}
        self.assertEqual(bundle_loop.dense_step(ff, np.array([[1, 0], [0, 1]]))[0].tolist(), [[3], [1]])     # 2 − 1 ≥ 1 fires. −2 − 1 does not
        layers = {'layers': [{'W': [[1, 1]], 'th': [3], 'k': 1}]}
        self.assertEqual(bundle_loop.layers_scores(layers, np.array([[1, 1], [1, 0]])).tolist(), [[1], [-1]])
        self.assertEqual(bundle_loop.decode_bits(np.array([[1, 0, 1]])).tolist(), [5.0])


