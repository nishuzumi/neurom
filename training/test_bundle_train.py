class StartsFromInit(unittest.TestCase):
    """A run from `init` (ADR 0020) starts at the integers of the init model (bundles.json `*Init`)."""

    def test_the_first_evaluation_is_the_start_that_the_browser_recorded(self):
        self.assertEqual(len(STARTS), 3)
        for fx in STARTS:
            with self.subTest(case=fx['name']):
                result = bt.train_bundle(bundle(fx['name'], epochs=1, evalEvery=1))
                self.assertEqual(result['evaluation']['evaluations'][0], {'epoch': 0, **fx['summary']})
                self.assertGreaterEqual(result['evaluation']['metric'], fx['summary']['metric'])

    def test_the_start_integers_are_the_init_model_exactly(self):
        for name, build in (('reinforceInit', bt.build_dense), ('crossEntropyInit', bt.build_dense), ('hingeInit', bt.build_threshold)):
            with self.subTest(case=name):
                b = bundle(name)
                model = build(trained(b)[0]['structure'], 1)
                model.restore(b['init']['model'])
                self.assertEqual(model.export(), b['init']['model'])

    def test_an_unbeaten_start_is_the_selected_model_unchanged(self):
        b = bundle('reinforceInit', epochs=2, evalEvery=1, replicas=1, episodesPerEpoch=8)
        result = bt.train_bundle(b)
        self.assertEqual(result['evaluation']['metric'], 3)                      # the init model already reaches the target count
        self.assertEqual(result['evaluation']['selectedEpoch'], 0)
        self.assertEqual(result['model'], b['init']['model'])
        first = bt.train_bundle(bundle('hinge', epochs=50, evalEvery=10, lr=0.05))         # a Python-trained artifact as the start
        again = bt.train_bundle(dict(bundle('hinge', epochs=5, evalEvery=5), init={'artifactId': '0x' + 'ab' * 32, 'model': first['model']}))
        self.assertEqual(again['evaluation']['evaluations'][0]['metric'], first['evaluation']['metric'])
        self.assertGreaterEqual(again['evaluation']['metric'], first['evaluation']['metric'])

    def test_an_init_model_must_fit_the_trained_network(self):
        b = bundle('crossEntropyInit'); b['init']['model']['layers'][0]['hidden'] = 4
        with self.assertRaisesRegex(bt.BundleError, 'init'): bt.validate_bundle(b)
        b = bundle('crossEntropyInit'); b['init'] = {'artifactId': '0x00'}
        with self.assertRaisesRegex(bt.BundleError, 'init'): bt.validate_bundle(b)



class Contract(unittest.TestCase):
    def test_validation_matches_the_browser_under_both_labelling_rules(self):
        self.assertEqual({fx['labelled'] for fx in VALIDATIONS}, {'all', 'any'})
        for fx in VALIDATIONS:
            with self.subTest(case=fx['name'], accuracy=fx['summary']['accuracy']):
                self.assertEqual(bt.Session(fx['bundle'], None).validate(fx['model'], labelled_any=fx['labelled'] == 'any'), fx['summary'])

    def test_hinge_rolls_every_seed_episode_once_like_the_browser(self):
        """frontend/training/hinge.js rolls episodesOf(training) out once: episodesPerEpoch / replicas do not apply."""
        class Rolled(Exception): pass
        rolled = []

        def run_steps(_session, episodes, intercept, before=None, record=False):
            rolled.append(episodes); raise Rolled

        with mock.patch.object(bt.Session, 'run_steps', run_steps):
            for recipe in ({'replicas': 1, 'episodesPerEpoch': 1}, {'replicas': 8, 'episodesPerEpoch': 64}):
                b = bundle('hinge', **recipe); b['partitions']['training'] = {'kind': 'seed', 'seed': 5, 'count': 3}
                with self.assertRaises(Rolled): bt.train_bundle(b)
        self.assertEqual(rolled, [[{'seed': 5}, {'seed': 6}, {'seed': 7}]] * 2)

    def test_method_requirements_are_enforced(self):
        b = bundle('reinforce'); net = trained(b)[0]['structure']; net['engine'] = 'threshold-layers'; net['layers'] = [4]
        with self.assertRaisesRegex(bt.BundleError, 'engine'): bt.validate_bundle(b)
        b = bundle('reinforce'); trained(b)[1]['readout'] = {'mode': 'bits', 'width': 2, 'decode': 'lsb-int'}
        with self.assertRaisesRegex(bt.BundleError, 'readout'): bt.validate_bundle(b)
        b = bundle('reinforce'); b['recipe']['method'] = 'cross-entropy'
        with self.assertRaisesRegex(bt.BundleError, 'target objective'): bt.validate_bundle(b)
        b = bundle('frozenGates'); next(n for nid, n in b['loop']['nodes'].items() if n['kind'] == 'network' and nid != b['loop']['trained'])['model'] = None
        with self.assertRaisesRegex(bt.BundleError, 'accepted weights'): bt.validate_bundle(b)
        b = bundle('frozenGates'); b['loop']['trained'] = next(nid for nid, n in b['loop']['nodes'].items() if n['kind'] == 'bits')
        with self.assertRaisesRegex(bt.BundleError, 'loop.trained'): bt.validate_bundle(b)
        b = bundle('reinforce'); b['objective'] = dict(BUNDLES['crossEntropy']['objective'], kind='reward')
        with self.assertRaises(bt.BundleError): bt.validate_bundle(b)         # a target program does not type-check as fn(Transition)→number
        b = bundle('reinforce'); b['format'] = 'nope'
        with self.assertRaisesRegex(bt.BundleError, 'format'): bt.validate_bundle(b)
        b = bundle('reinforce', lr=5)
        with self.assertRaisesRegex(bt.BundleError, 'recipe.lr'): bt.validate_bundle(b)
        b = bundle('reinforce'); trained(b)[1]['readout']['map'] = [0, 7]
        with self.assertRaisesRegex(bt.BundleError, 'action 7'): bt.validate_bundle(b)
        self.assertEqual(bt.validate_bundle(bundle('hinge'))['method'], 'hinge')

    def test_tool_layers_train_by_reinforce_only(self):
        b = bundle('gate'); b['recipe']['method'] = 'cross-entropy'
        with self.assertRaisesRegex(bt.BundleError, 'reinforce only'): bt.validate_bundle(b)
        b = bundle('gate'); trained(b)[1]['readout'] = {'mode': 'argmax', 'map': [0]}
        with self.assertRaisesRegex(bt.BundleError, 'needs the bits readout'): bt.validate_bundle(b)

    def test_python_trained_models_replay_in_the_browser_executor_with_the_same_decisions(self):
        for fx in REPLAYS:
            with self.subTest(**fx['source']):
                b = fx['bundle']
                summary, steps = replay(b, fx['model'])
                self.assertEqual(summary, fx['summary'])
                self.assertEqual(bt.Session(b, None).validation, [d['start'] for d in fx['decisions']])
                for got, js in zip(steps, fx['decisions']): self.assertEqual(got, js['steps'], js['start'])

    def test_the_trainer_forward_pass_is_the_integer_step(self):
        torch = bt._torch()

        class Tool:                                                             # choice 0 → [d0 | d1, 1], choice 1 → [d0 & d2] (zero-extended). No state
            width = 0

            def __call__(self, port, choice, data, S=None):
                return np.where((choice == 1)[:, None], np.stack([data[:, 0] & data[:, 2], 0 * data[:, 0]], 1), np.stack([data[:, 0] | data[:, 1], 1 + 0 * data[:, 0]], 1))
        tool = Tool()
        T = {'tools': 'tools', 'K': 2, 'D': 3, 'R': 2}
        shapes = {'two': [{'hidden': 7}, {'hidden': 4}], 'between': [{'hidden': 7}, T, {'hidden': 4}], 'trailing': [{'hidden': 7}, T], 'first': [T, {'hidden': 4}]}
        for bits in (8, 16):
            for kind, shape in (('feedforward', FF), ('lif', dict(LIF, ticks=3))):
                for name, layers in shapes.items():
                    with self.subTest(bits=bits, kind=kind, shape=name):
                        net = {'engine': 'dense-policy', 'inputs': 5, 'outputs': 2 if name == 'trailing' else 3, 'weightBits': bits, **shape, 'layers': layers}
                        model = bt.build_dense(net, 1)
                        X = np.random.default_rng(2).integers(0, 2, size=(16, 5))
                        bt.init_dense(model, 1, 0.5, X.astype(np.float64), call=tool, sample=torch.Generator().manual_seed(3))
                        g = torch.Generator().manual_seed(1)
                        with torch.no_grad():                                   # nonzero head biases too (init leaves them 0): the ×ticks factor is exercised
                            for p in model.P: p.add_(torch.randn(p.shape, generator=g, dtype=torch.float64) * 0.1)
                        m = bt.validate_model(model.export(), net)
                        if bits == 8: self.assertTrue(any(L.get('k', L.get('k_c', 0)) > 0 for L in m['layers']), 'the shift is exercised')
                        V, Vi, choices = model.new_state(16), np.zeros((16, bundle_loop.dense_state_width(m)), dtype=np.int64), set()
                        for _ in range(3):                                      # an episode: voltages carry over (LIF)
                            with torch.no_grad(): out = model.decide(torch.from_numpy(X.astype(np.float64)), V if kind == 'lif' else model.new_state(16), call=tool)
                            scores, counts, Vi, tools = bundle_loop.dense_step(m, X, Vi if kind == 'lif' else None, tool)
                            self.assertTrue(np.array_equal(out['scores'].numpy(), scores)); self.assertTrue(np.array_equal(out['counts'].numpy(), counts))
                            if kind == 'lif': self.assertTrue(np.array_equal(out['V'].numpy(), Vi)); V = out['V']
                            for d, r in zip(out['decisions'], (tools or {}).values()):
                                for key in ('choice', 'data', 'result'): self.assertTrue(np.array_equal(d[key], r[key]), key)
                                choices |= set(r['choice'].tolist())
                        self.assertGreater(counts[:, -4:].sum(), 0, 'the last plain layer fires')
                        if name != 'two': self.assertEqual(choices, {0, 1}, 'both tools are chosen on some input')

    def test_the_trainer_keeps_each_lanes_tool_state_like_the_executor(self):
        """REINFORCE's network inside the loop (_DenseLanes) calls a LIF network tool from each lane's own tool state:
        bit-exact with bundle_loop.dense_step on the caller's full state (own potentials ‖ tool states), advanced only on
        the lanes that run and choose that tool."""
        torch = bt._torch()
        lif_tool = {'kind': 'net', 'readout': {'mode': 'bits', 'width': 2, 'decode': 'lsb-int'}, 'structure': {'inputs': 3},
                    'model': {'format': 'dense-policy', 'kind': 'lif', 'inputs': 3, 'outputs': 2, 'weightBits': 8, 'ticks': 1, 'leak_shift': 2, 'reset': 0,
                              'layers': [{'hidden': 2, 'W': [[1, 1, 0], [0, 1, 1]], 'b': [0, 0], 'scale': 1, 'k': 0, 'threshold': 3}], 'output': {'W': [[1, 0], [0, 1]], 'b': [-1, -1], 'scale': 1, 'k': 0}}}
        or_tool = {'kind': 'net', 'readout': {'mode': 'bits', 'width': 2, 'decode': 'lsb-int'}, 'structure': {'inputs': 2},
                   'model': {'format': 'threshold-layers', 'inputs': 2, 'outputs': 2, 'weightBits': 8, 'layers': [{'W': [[1, 1], [1, 0]], 'th': [1, 1], 'scale': 1, 'k': 0}]}}
        T = {'tools': 'tools', 'K': 2, 'D': 3, 'R': 2}
        caller = bundle_loop.ToolCaller('net', {'structure': {'layers': [T]}, 'tools': {'tools': [lif_tool, or_tool]}})
        self.assertEqual(caller.width, 2)
        for kind, shape in (('feedforward', FF), ('lif', dict(LIF, ticks=2))):
            with self.subTest(kind=kind):
                net = {'engine': 'dense-policy', 'inputs': 5, 'outputs': 2, 'weightBits': 8, **shape, 'layers': [{'hidden': 6}, T]}
                model = bt.build_dense(net, 1)
                rng = np.random.default_rng(5)
                bt.init_dense(model, 1, 0.5, rng.integers(0, 2, size=(16, 5)).astype(np.float64), call=caller, sample=torch.Generator().manual_seed(3))
                g = torch.Generator().manual_seed(2)
                with torch.no_grad():
                    for p in model.P: p.add_(torch.randn(p.shape, generator=g, dtype=torch.float64) * 0.3)
                m = bt.validate_model(model.export(), net)
                lanes_net, own = bt._DenseLanes(torch, model, 16, caller), bundle_loop.own_state_width(m)
                full, moved = np.zeros((16, own + caller.width), dtype=np.int64), 0
                for t in range(8):
                    X, lanes = rng.integers(0, 2, size=(16, 5)), rng.random(16) < 0.7
                    before = lanes_net.S.copy()
                    with torch.no_grad(): out, _ = lanes_net.decide(X.astype(np.float64), lanes)
                    scores, _, full[lanes], _ = bundle_loop.dense_step(m, X[lanes], full[lanes], caller)
                    self.assertTrue(np.array_equal(out['scores'].numpy()[lanes], scores), f'step {t} scores')
                    self.assertTrue(np.array_equal(lanes_net.S, full[:, own:]), f'step {t} tool states')
                    if own: self.assertTrue(np.array_equal(lanes_net.V.numpy(), full[:, :own]), f'step {t} own potentials')
                    keep = ~(lanes & (out['decisions'][0]['choice'] == 0))                 # did not run, or chose the OR tool
                    self.assertTrue(np.array_equal(lanes_net.S[keep], before[keep]), f'step {t}: unchosen tool states are untouched')
                    moved += int((lanes_net.S != before).any(axis=1).sum())
