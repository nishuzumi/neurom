"""bundle_train.py. These tests check that:
    - every method learns its tiny fixture bundle (training/fixtures/bundles.json, generated by
      training/fixtures/bundle-env.mjs).
    - two-layer dense nets train with every dense method.
    - cross-entropy trains a network wider than 256 (1020 inputs, a layer of 300, 300 actions, ADR 0021).
    - REINFORCE trains through tool layers (the gate task, a reward reading transition.loop, a nested network tool, a LIF
      network tool whose state each lane keeps, the builtin combiner).
    - a policy learns on the outputs of frozen networks inside its loop.
    - exported models are exactly what the integer loop evaluated and replay identically in the browser executor
      (training/fixtures/replays.json).
    - validation counts accuracy as the browser does under both labelling rules (bundle-env.json `validations`).
    - bundles that break the method requirements are refused.
    - runs are deterministic, cancellable and bounded in progress traffic."""
import json
import tempfile
import unittest
from pathlib import Path
from unittest import mock

import numpy as np

import bundle_loop
import bundle_train as bt

ROOT = Path(__file__).resolve().parent
BUNDLES = json.loads((ROOT / 'fixtures' / 'bundles.json').read_text())
FIXTURES = json.loads((ROOT / 'fixtures' / 'bundle-env.json').read_text())
VALIDATIONS, STARTS = FIXTURES['validations'], FIXTURES['starts']
REPLAYS = json.loads((ROOT / 'fixtures' / 'replays.json').read_text())['replays']


def artifact_bundle(name):
    """The trainer bundle a builtin artifact (frontend/templates/artifacts) was trained on."""
    return json.loads((ROOT.parent / 'frontend' / 'templates' / 'artifacts' / f'{name}.json').read_text())['bundle']


def replay(b, model):
    """Greedy Python loop of `model` as b's trained network on the validation episodes → (summary, per-episode steps of
    {action, tools}) — the shape of the browser replays in replays.json."""
    s = bt.Session(b, None)
    lx = bundle_loop.create_loop(b['loop'], models={s.trained: model})
    steps = [[] for _ in s.validation]

    def on_step(state, out, tr):
        for i in np.flatnonzero(tr['active']):
            tools = {nid: {port: {k: (a[i].tolist() if a.ndim > 1 else float(a[i])) for k, a in r.items()} for port, r in rec.items()} for nid, rec in out['tools'].items() if out['ran'][nid][i]}
            steps[i].append({'action': float(out['action'][i]), 'tools': tools})

    bundle_loop.run_episodes(s.env, lx, s.validation, reward=s.reward, on_step=on_step)
    return s.validate(model), steps


def bundle(name, **recipe):
    b = json.loads(json.dumps(BUNDLES[name]))
    b['recipe'].update(recipe)
    return b


TWO_LAYERS = [{'hidden': 8}, {'hidden': 6}]
FF = {'kind': 'feedforward', 'ticks': 1, 'leak_shift': 0, 'reset': 0}
LIF = {'kind': 'lif', 'ticks': 2, 'leak_shift': 2, 'reset': 0}


def trained(b):
    """(network node, readout node) of the bundle's trained network."""
    nid, _, rid, _ = bt.trained_parts(b)
    return b['loop']['nodes'][nid], b['loop']['nodes'][rid]


class Learns(unittest.TestCase):
    def check_result(self, b, result, model_format):
        self.assertEqual(result['model']['format'], model_format)
        bt.validate_result(b, result['model'], result['evaluation'], result['provenance'])
        ev, prov = result['evaluation'], result['provenance']
        self.assertEqual(prov['backend'], 'python'); self.assertEqual(prov['method'], b['recipe']['method']); self.assertEqual(prov['bundleHash'], '0xhash')
        self.assertEqual(set(ev) >= {'metricName', 'metric', 'selectedEpoch', 'curves', 'validation'}, True)
        self.assertEqual(len(ev['curves']['loss']), min(ev['selection'].get('epochsRun', b['recipe']['epochs']), bt.CURVE_POINTS))   # hinge stops early once exact
        # the reported validation summary is reproducible from the exported integer model alone
        again = bt.Session(b, None).validate(result['model'], labelled_any=b['recipe']['method'] != 'hinge')
        self.assertEqual(again, ev['validation'])
        # every region of the exported model in blob order: its scale, shift, clip counts (and LIF threshold). Nothing clips
        m, q = result['model'], ev['quantization']
        want = []
        for i, L in enumerate(m['layers']):
            if 'tools' in L: want += [(f'layers[{i}].choice', L['scale_c'], L['k_c'], None), (f'layers[{i}].data', L['scale_d'], L['k_d'], None)]
            else: want.append((f'layers[{i}]', L['scale'], L['k'], L.get('threshold')))
        if m.get('output'): want.append(('output', m['output']['scale'], m['output']['k'], None))
        self.assertEqual([(e['region'], e['scale'], e['k'], e.get('threshold')) for e in q], want)
        self.assertEqual([e['clippedWeights'] for e in q], [0] * len(q))

    def test_reinforce_learns_to_count_up(self):
        b = bundle('reinforce', epochs=30, evalEvery=10, replicas=1, episodesPerEpoch=32, lr=0.05)
        result = bt.train_bundle(b, bundle_hash='0xhash')
        self.check_result(b, result, 'dense-policy')
        self.assertEqual(result['evaluation']['metricName'], 'validationMeanReturn')
        self.assertGreaterEqual(result['evaluation']['validation']['successRate'], 0.9)
        self.assertGreaterEqual(result['evaluation']['metric'], 2.5)

    def test_cross_entropy_learns_the_teacher_mask(self):
        b = bundle('crossEntropy', epochs=15, evalEvery=5, replicas=1, episodesPerEpoch=16, lr=0.05)
        result = bt.train_bundle(b, bundle_hash='0xhash')
        self.check_result(b, result, 'dense-policy')
        self.assertEqual(result['evaluation']['metricName'], 'validationAccuracy')
        self.assertEqual(result['model']['kind'], 'feedforward')
        self.assertGreaterEqual(result['evaluation']['metric'], 0.95)
        self.assertEqual(result['evaluation']['validation']['labelledSteps'], 96)      # 32 episodes × 3 labelled steps

    def test_cross_entropy_trains_a_network_wider_than_256(self):
        """ADR 0021: 1020 input bits, a layer of 300 and 300 actions (frontend/core/fixtures/wide.js). The actions 297,
        296 and 295 are above 255."""
        b = bundle('wide')
        result = bt.train_bundle(b, bundle_hash='0xhash')
        self.check_result(b, result, 'dense-policy')
        m = result['model']
        self.assertEqual((m['inputs'], m['layers'][0]['hidden'], m['outputs']), (1020, 300, 300))
        self.assertEqual(result['evaluation']['metric'], 1)
        self.assertEqual(result['evaluation']['validation']['successRate'], 1)

    def test_hinge_learns_the_two_bit_adder(self):
        b = bundle('hinge', epochs=300, evalEvery=25, replicas=1, lr=0.05)
        trained(b)[0]['structure']['layers'] = [16]
        result = bt.train_bundle(b, bundle_hash='0xhash')
        self.check_result(b, result, 'threshold-layers')
        self.assertGreaterEqual(result['evaluation']['metric'], 0.9)
        if result['evaluation']['metric'] == 1: self.assertLess(result['evaluation']['selection']['epochsRun'], 300)
        self.assertEqual([len(L['th']) for L in result['model']['layers']], [16, 3])

    def test_reinforce_trains_a_policy_on_the_outputs_of_frozen_networks(self):
        b = bundle('frozenGates', epochs=60, evalEvery=10, replicas=8, lr=0.05)
        frozen = {nid: n['model'] for nid, n in b['loop']['nodes'].items() if n['kind'] == 'network' and nid != b['loop']['trained']}
        self.assertEqual(len(frozen), 2)
        result = bt.train_bundle(b, bundle_hash='0xhash')
        self.check_result(b, result, 'dense-policy')
        self.assertEqual((result['model']['inputs'], result['model']['outputs']), (6, 2))
        self.assertEqual(result['evaluation']['validation']['successRate'], 1.0)
        self.assertEqual({nid: n['model'] for nid, n in b['loop']['nodes'].items() if nid in frozen}, frozen)

    def test_two_layer_dense_nets_train_with_every_dense_method(self):
        for kind, shape in (('feedforward', FF), ('lif', LIF)):
            with self.subTest(kind=kind, method='reinforce'):
                b = bundle('reinforce', epochs=30, evalEvery=10, replicas=1, episodesPerEpoch=32, lr=0.05)
                trained(b)[0]['structure'].update(shape, layers=TWO_LAYERS)
                result = bt.train_bundle(b, bundle_hash='0xhash')
                self.check_result(b, result, 'dense-policy')
                self.assertEqual([L['hidden'] for L in result['model']['layers']], [8, 6])
                self.assertGreaterEqual(result['evaluation']['metric'], 2.5)
            with self.subTest(kind=kind, method='cross-entropy'):
                b = bundle('crossEntropy', epochs=15, evalEvery=5, replicas=1, episodesPerEpoch=16, lr=0.05)
                trained(b)[0]['structure'].update(shape, layers=TWO_LAYERS)
                result = bt.train_bundle(b, bundle_hash='0xhash')
                self.check_result(b, result, 'dense-policy')
                self.assertEqual(result['model']['kind'], kind)
                self.assertGreaterEqual(result['evaluation']['metric'], 0.95)

    def test_reinforce_through_a_tool_layer_reaches_greedy_success(self):
        for name, kind in (('gate', 'feedforward'), ('gate', 'lif'), ('gateAfter', 'feedforward')):
            with self.subTest(bundle=name, kind=kind):
                b = bundle(name)
                if kind == 'lif': trained(b)[0]['structure'].update(LIF, ticks=3)
                result = bt.train_bundle(b, bundle_hash='0xhash')
                self.check_result(b, result, 'dense-policy')
                self.assertEqual(result['evaluation']['validation']['successRate'], 1.0)
                self.assertEqual([L.get('tools', L.get('hidden')) for L in result['model']['layers']], [8, 'tools'] + ([4] if name == 'gateAfter' else []))
                self.assertEqual('output' in result['model'], name == 'gateAfter')

    def test_reinforce_trains_a_selector_over_a_nested_tool_and_over_a_lif_tool(self):
        """ADR 0014, any network is a tool: gateNested's AND is a network with its own tool layer (over the threshold AND
        gate). gateLif's OR is a LIF network over two-step episodes, its potential carried per lane between them."""
        nested = bundle('gateNested'); tools = trained(nested)[0]['tools']['tools']
        self.assertEqual([(t['kind'], [u['kind'] for u in t.get('tools', {}).get('tools', [])]) for t in tools], [('net', ['net']), ('program', [])])
        lif = bundle('gateLif'); tools = trained(lif)[0]['tools']['tools']
        self.assertEqual([(t['kind'], t.get('structure', {}).get('kind')) for t in tools], [('program', None), ('net', 'lif')])
        for name, kind in (('gateNested', 'feedforward'), ('gateNested', 'lif'), ('gateLif', 'feedforward'), ('gateLif', 'lif')):
            with self.subTest(bundle=name, kind=kind):
                b = bundle(name)
                if kind == 'lif': trained(b)[0]['structure'].update(LIF, ticks=3)
                result = bt.train_bundle(b, bundle_hash='0xhash')
                self.check_result(b, result, 'dense-policy')
                v = result['evaluation']['validation']
                self.assertEqual((v['successRate'], v['meanSteps'], v['meanReturn']), (1.0, 2.0, 2.0) if name == 'gateLif' else (1.0, 1.0, 1.0))

    def test_the_reward_reads_the_tool_layer_records_through_transition_loop(self):
        b = bundle('gateLoop')
        result = bt.train_bundle(b, bundle_hash='0xhash')
        self.check_result(b, result, 'dense-policy')
        self.assertGreater(result['evaluation']['curves']['trainReturn'][-1], 1.5, 'the sampled decisions earn the bonus (success alone is at most 1)')
        self.assertEqual(result['evaluation']['metric'], 2.0, 'the greedy policy hands a‖b and answers right')

    def test_reinforce_trains_the_builtin_combiner_to_validation_one(self):
        b = artifact_bundle('arithmetic-combiner-policy')                       # its template's recipe: 100 epochs, lr 0.1, entropy 0.03
        result = bt.train_bundle(b, bundle_hash='0xhash')
        self.check_result(b, result, 'dense-policy')
        self.assertEqual(result['evaluation']['validation']['successRate'], 1.0)
        self.assertEqual(result['evaluation']['metric'], 1.0)

    def test_same_seed_same_model(self):
        b = bundle('reinforce', epochs=5, evalEvery=5, replicas=1, episodesPerEpoch=8)
        a, c = bt.train_bundle(b), bt.train_bundle(b)
