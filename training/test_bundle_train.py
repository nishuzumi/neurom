    def test_exported_model_is_rejected_when_it_disagrees_with_the_structure(self):
        net = {'engine': 'dense-policy', 'inputs': 3, 'outputs': 2, 'weightBits': 8, **FF, 'layers': [{'hidden': 4}]}
